/*
 * 文件名：operator_precedence.c
 * 内容：运算符优先级与求值顺序
 *
 * 优先级（从高到低，越靠上越早算）：
 *   括号 ()
 *   单目 ++ -- ! -负号 sizeof
 *   乘除余 * / %
 *   加减 + -
 *   大小比较 < <= > >=
 *   等于不等于 == !=
 *   逻辑与 &&
 *   逻辑或 ||
 *   赋值 = += -=
 */

#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

int main(void)
{
    /* ========== 规则 1：括号最高 ========== */

    int r1 = 2 + 3 * 4;     // 先乘后加 = 14
    int r2 = (2 + 3) * 4;   // 括号先算 = 20

    printf("=== 1. parentheses ===\n");
    printf("2 + 3 * 4 = %d\n", r1);     // 14
    printf("(2 + 3) * 4 = %d\n\n", r2); // 20

    /* ========== 规则 2：单目 ++ -- ! 仅次于括号 ========== */

    int i = 5;
    int r3 = i++ * 2;   // 先取 i++ 的值(5)，再 *2；然后 i 变成 6

    int flag = 0;
    int r4 = !flag;     // ! 取反：!0 = 1, !1 = 0

    printf("=== 2. unary operators ===\n");
    printf("i++ * 2 = %d, i = %d\n", r3, i); // 10, 6
    printf("!0 = %d, !1 = %d\n\n", r4, !1);  // 1, 0

    /* ========== 规则 3：乘除余 高于 加减 ========== */

    int r5 = 10 - 6 / 2;    // 先 6/2=3，再 10-3 = 7
    int r6 = 10 % 3 * 2;    // % 和 * 同级，从左到右：10%3=1，1 * 2 = 2

    printf("=== 3. * / %% before + - ===\n");
    printf("10 - 6 / 2 = %d\n", r5);   // 7
    printf("10 %% 3 * 2 = %d\n\n", r6); // 2
    // 注意：printf 里想输出一个 % 必须写成 %%，否则编译器会把它当成格式符而告警

    /* ========== 规则 4：大小比较 高于 == != ========== */

    int r7 = 3 + 2 == 5;   // 先 3+2=5，再 5==5 → 1（真）
    int r8 = (5 > 3) == 1;   // 先 5>3=1，再 1==1 → 1（真）
    // 这里不加括号也能算对，但编译器会警告"建议在 == 两边加括号"
    // 因为 5 > 3 == 1 这种连写可读性差，所以实际写代码时建议加上括号

    printf("=== 4. comparison before == and != ===\n");
    printf("3 + 2 == 5 -> %d\n", r7); // 1
    printf("(5 > 3) == 1 -> %d\n\n", r8); // 1

    /* ========== 规则 5：&& 高于 || ========== */

    int r9 = 0 || (1 && 0);   // 先 1&&0=0，再 0||0 = 0
    // 同理：编译器会警告"建议在 || 内的 && 两边加括号"
    // 虽然不加括号结果也对（因为 && 优先级本来就高于 ||），
    // 但加上括号能明确表达意图，读代码的人不会误判

    printf("=== 5. && before || ===\n");
    printf("0 || (1 && 0) = %d\n\n", r9); // 0

    /* ========== 规则 6：赋值 = 优先级最低 ========== */

    int u, v;
    u = v = 5;       // 从右到左：v=5，再 u=5
    int w = 2 + 3;   // 先算 2+3=5，再赋值，不会先赋值再相加

    printf("=== 6. assignment is last ===\n");
    printf("u = v = 5  -> u=%d, v=%d\n", u, v); // 5, 5
    printf("w = 2 + 3  -> w=%d\n\n", w);         // 5

    /* ========== 规则 7：结合性 =========
     *
     * 同级运算符"谁先算"由结合性决定：
     *   + - * / %          从左到右
     *   赋值 = 及其复合形式   从右到左
     *   单目运算符           从右到左
     *
     * 例：10 - 3 - 2 = (10 - 3) - 2 = 5
     *     2 * 3 / 2 = (2 * 3) / 2 = 3
     *
     * 注意：同级先算只保证运算符的结合方向，
     *      不保证操作数里函数调用/自增的求值顺序。
     *      凡是有副作用的操作，不要依赖顺序。
     */

    int r10 = 10 - 3 - 2;  // 从左到右：(10-3)-2 = 5
    int r11 = 2 * 3 / 2;   // 从左到右：(2 * 3)/2 = 3

    printf("=== 7. associativity ===\n");
    printf("10 - 3 - 2 = %d\n", r10); // 5
    printf("2 * 3 / 2 = %d\n\n", r11); // 3

    /* ========== 三大常见坑 ========== */
    /*
     * 坑 1：== 是比较，= 是赋值，写反是大坑
     *   if (a = 5)   错：把 5 赋给 a，再判断 a 是否为真
     *   if (a == 5)  对：这才是比较
     *
     * 坑 2：位运算和比较混用要加括号
     *   if (a & b == 0)  错：等价于 a & (b == 0)
     *   if ((a & b) == 0) 对
     *
     * 坑 3：一个表达式里又用又改同一个变量
     *   i++ + ++i     结果不确定，别写
     */

    int a = 3;
    int check = (a == 5);  // 比较：3 == 5 为假，结果是 0

    printf("=== traps ===\n");
    printf("a == 5 -> %d (0 means false)\n", check); // 0

    return 0;
}
